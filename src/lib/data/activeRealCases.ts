function createDocumentList(caseNumber: string, dateStr: string): DocumentItem[] {
  return INITIAL_DOCUMENT_TEMPLATES.map((tmpl) => {
    if (['doc-1', 'doc-2', 'doc-3', 'doc-4'].includes(tmpl.id)) {
      return {
        ...tmpl,
        id: `${tmpl.id}-${caseNumber}`,
        status: 'completed' as const,
        lastUpdated: `${dateStr} 10:00 AM`
      };
    }
    if (tmpl.id === 'doc-5') {
      return {
        ...tmpl,
        id: `${tmpl.id}-${caseNumber}`,
        status: 'signed' as const,
        lastUpdated: `${dateStr} 01:00 PM`
      };
    }
    if (tmpl.id === 'doc-8') {
      return {
        ...tmpl,
        id: `${tmpl.id}-${caseNumber}`,
        status: 'signed' as const,
        lastUpdated: `${dateStr} 02:00 PM`
      };
    }
    if (tmpl.id === 'doc-10') {
      return {
        ...tmpl,
        id: `${tmpl.id}-${caseNumber}`,
        status: 'approved' as const,
        lastUpdated: `${dateStr} 03:00 PM`
      };
    }
    return {
      ...tmpl,
      id: `${tmpl.id}-${caseNumber}`
    };
  });
}

